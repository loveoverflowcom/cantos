#!/usr/bin/env python3
"""Generate trusted Leptos SVG and CMP path data from the licensed offline subset."""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "packages/ui-system/shared/icons/material-outlined"
OUTPUT = ROOT / "packages/ui-system/leptos/src/icons.rs"
CMP_OUTPUT = ROOT / "packages/ui-system/cmp/src/commonMain/kotlin/com/cantos/ui/generated/CantosIcons.kt"
ALLOWED = {"path": {"d", "fill", "opacity"}, "rect": {"x", "y", "width", "height", "fill"}, "g": {"fill"}}


def variant(name):
    return "".join(part.title() for part in name.split("_"))


def node_markup(node):
    tag = node.tag.removeprefix("{http://www.w3.org/2000/svg}")
    if tag not in ALLOWED or not set(node.attrib) <= ALLOWED[tag]:
        raise ValueError("unsupported SVG anatomy")
    if node.text and node.text.strip():
        raise ValueError("SVG text is not allowed")
    attributes = " ".join(f'{key}={json.dumps(value)}' for key, value in sorted(node.attrib.items()))
    children = "".join(node_markup(child) for child in node)
    return f"<{tag} {attributes}>{children}</{tag}>"


def render():
    manifest = json.loads((ASSETS / "manifest.json").read_text())
    names = sorted(manifest["icons"])
    lines = [
        "// Generated by python3 scripts/ui_icons.py. Do not edit.",
        "// Google Material Icons Outlined; Apache-2.0. See shared/icons/material-outlined/.",
        "use leptos::prelude::*;", "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub enum IconName {",
    ]
    lines.extend(f"    {variant(name)}," for name in names)
    lines += ["}", "", "impl IconName {", "    pub const ALL: &'static [Self] = &["]
    lines.extend(f"        Self::{variant(name)}," for name in names)
    lines += ["    ];", "", "    pub const fn as_str(self) -> &'static str {", "        match self {"]
    lines.extend(f'            Self::{variant(name)} => "{name}",' for name in names)
    lines += ["        }", "    }", "}", "", "/// Decorative only. The parent control or adjacent text owns the localized name.",
              "#[component]", "pub fn Icon(name: IconName) -> impl IntoView {", "    view! {",
              '        <svg class="cui-icon" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"',
              '            fill="currentColor" aria-hidden="true" focusable="false">',
              "            {match name {"]
    for name in names:
        raw = (ASSETS / (name + ".svg")).read_bytes()
        if hashlib.sha256(raw).hexdigest() != manifest["icons"][name]["sha256"]:
            raise ValueError(f"icon source hash mismatch: {name}")
        svg = ET.fromstring(raw)
        if svg.attrib.get("viewBox") != "0 0 24 24":
            raise ValueError("unsupported SVG viewBox")
        anatomy = "".join(node_markup(child) for child in svg)
        lines.append(f"                IconName::{variant(name)} => view! {{ <g>{anatomy}</g> }}.into_any(),")
    lines += ["            }}", "        </svg>", "    }", "}", ""]
    return "\n".join(lines)


def render_kotlin():
    manifest = json.loads((ASSETS / "manifest.json").read_text())
    lines = ["// Generated by python3 scripts/ui_icons.py. Do not edit.",
             "// Google Material Icons Outlined; Apache-2.0. See shared/icons/material-outlined/.",
             "package com.cantos.ui.generated", "",
             "data class CantosIcon(val name: String, val viewBox: String, val pathData: List<String>)", "",
             "object CantosIcons {", "    val icons: List<CantosIcon> = listOf("]
    for name in sorted(manifest["icons"]):
        raw = (ASSETS / (name + ".svg")).read_bytes()
        if hashlib.sha256(raw).hexdigest() != manifest["icons"][name]["sha256"]:
            raise ValueError(f"icon source hash mismatch: {name}")
        svg = ET.fromstring(raw)
        if svg.attrib.get("viewBox") != "0 0 24 24":
            raise ValueError("unsupported SVG viewBox")
        for child in svg:
            node_markup(child)  # Reuse the trusted-anatomy barrier before rendering another target.
        paths = []
        for node in svg.iter():
            tag = node.tag.removeprefix("{http://www.w3.org/2000/svg}")
            if tag == "path" and node.attrib.get("fill") != "none":
                if set(node.attrib) != {"d"}:
                    raise ValueError("CMP icon mapping requires plain filled path anatomy")
                paths.append(node.attrib["d"])
            elif tag == "g" and not node.attrib:
                pass  # Plain groups only contain the same trusted paths.
            elif tag == "rect" and node.attrib.get("fill") == "none":
                pass  # Non-painted viewBox rect; no geometry is silently lost.
            elif tag not in ("svg", "path"):
                raise ValueError("CMP icon mapping cannot silently omit non-path anatomy")
        if not paths:
            raise ValueError(f"CMP icon has no visible paths: {name}")
        path_data = ", ".join(json.dumps(path) for path in paths)
        lines.append(f'        CantosIcon("{name}", "0 0 24 24", listOf({path_data})),')
    lines += ["    )", "    fun paths(name: String): List<String> =",
              '        requireNotNull(icons.find { it.name == name }) { "Unknown icon: $name" }.pathData', "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = {OUTPUT: render(), CMP_OUTPUT: render_kotlin()}
    if args.check:
        if any(not path.exists() or path.read_text() != content for path, content in expected.items()):
            raise SystemExit("FAIL: generated icon drift")
        print("PASS: offline SVG hashes and generated Leptos/CMP anatomy agree")
    else:
        for path, content in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
