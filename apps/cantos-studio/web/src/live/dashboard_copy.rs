//! Studio overview copy; bounded catalog observations never imply portfolio totals.
use crate::localization::generated::dashboard as resources;
#[derive(Clone, Copy)]
pub enum Key {
    Title,
    NewWork,
    Import,
    Resume,
    Continue,
    NoSelection,
    SelectedUnit,
    Works,
    Refresh,
    Next,
    Previous,
    NotRead,
    Loading,
    ReadFailed,
    RetryHelp,
    EmptyTitle,
    EmptyHelp,
    More,
    End,
    Audio,
    AudioHelp,
    AudioNotRead,
    AudioAwaiting,
    AudioAdmitted,
    AudioRevoked,
    AudioExpired,
    AudioStale,
    OpenAudio,
    Candidate,
    Editor,
    EditorHelp,
    OpenEditor,
    Draft,
    Archived,
    UnknownLifecycle,
}

pub fn text(key: Key, locale: crate::localization::Locale) -> &'static str {
    match key {
        Key::UnknownLifecycle => resources::text(resources::Key::UnknownLifecycle, locale),
        Key::Title => resources::text(resources::Key::Title, locale),
        Key::NewWork => resources::text(resources::Key::NewWork, locale),
        Key::Import => resources::text(resources::Key::Import, locale),
        Key::Resume => resources::text(resources::Key::Resume, locale),
        Key::Continue => resources::text(resources::Key::Continue, locale),
        Key::NoSelection => resources::text(resources::Key::NoSelection, locale),
        Key::SelectedUnit => resources::text(resources::Key::SelectedUnit, locale),
        Key::Works => resources::text(resources::Key::Works, locale),
        Key::Refresh => resources::text(resources::Key::Refresh, locale),
        Key::Previous => resources::text(resources::Key::Previous, locale),
        Key::Next => resources::text(resources::Key::Next, locale),
        Key::NotRead => resources::text(resources::Key::NotRead, locale),
        Key::Loading => resources::text(resources::Key::Loading, locale),
        Key::ReadFailed => resources::text(resources::Key::ReadFailed, locale),
        Key::RetryHelp => resources::text(resources::Key::RetryHelp, locale),
        Key::EmptyTitle => resources::text(resources::Key::EmptyTitle, locale),
        Key::EmptyHelp => resources::text(resources::Key::EmptyHelp, locale),
        Key::More => resources::text(resources::Key::More, locale),
        Key::End => resources::text(resources::Key::End, locale),
        Key::Audio => resources::text(resources::Key::Audio, locale),
        Key::AudioHelp => resources::text(resources::Key::AudioHelp, locale),
        Key::AudioNotRead => resources::text(resources::Key::AudioNotRead, locale),
        Key::AudioAwaiting => resources::text(resources::Key::AudioAwaiting, locale),
        Key::AudioAdmitted => resources::text(resources::Key::AudioAdmitted, locale),
        Key::AudioRevoked => resources::text(resources::Key::AudioRevoked, locale),
        Key::AudioExpired => resources::text(resources::Key::AudioExpired, locale),
        Key::AudioStale => resources::text(resources::Key::AudioStale, locale),
        Key::OpenAudio => resources::text(resources::Key::OpenAudio, locale),
        Key::Candidate => resources::text(resources::Key::Candidate, locale),
        Key::Editor => resources::text(resources::Key::Editor, locale),
        Key::EditorHelp => resources::text(resources::Key::EditorHelp, locale),
        Key::OpenEditor => resources::text(resources::Key::OpenEditor, locale),
        Key::Draft => resources::text(resources::Key::Draft, locale),
        Key::Archived => resources::text(resources::Key::Archived, locale),
    }
}
