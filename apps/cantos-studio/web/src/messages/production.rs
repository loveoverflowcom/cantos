pub fn rights_status(
    status: crate::contract::ProductionRightsStatus,
    locale: crate::localization::Locale,
) -> &'static str {
    use crate::contract::ProductionRightsStatus;
    text(
        match status {
            ProductionRightsStatus::Pending => Key::Pending,
            ProductionRightsStatus::Granted => Key::Granted,
            ProductionRightsStatus::Revoked => Key::Revoked,
        },
        locale,
    )
}

pub fn finding(
    code: crate::contract::ProductionFindingCode,
    locale: crate::localization::Locale,
) -> &'static str {
    use crate::contract::ProductionFindingCode as F;
    match code {
        F::ScriptUnreviewed => resources::text(resources::Key::FindingScriptUnreviewed, locale),
        F::RightsMissing => resources::text(resources::Key::FindingRightsMissing, locale),
        F::RightsPending => resources::text(resources::Key::FindingRightsPending, locale),
        F::RightsRevoked => resources::text(resources::Key::FindingRightsRevoked, locale),
        F::RightsNotYetValid => resources::text(resources::Key::FindingRightsNotYetValid, locale),
        F::RightsExpired => resources::text(resources::Key::FindingRightsExpired, locale),
        F::RightsSubjectMismatch => {
            resources::text(resources::Key::FindingRightsSubjectMismatch, locale)
        }
        F::RightsLanguageMismatch => {
            resources::text(resources::Key::FindingRightsLanguageMismatch, locale)
        }
        F::RightsTerritoryMismatch => {
            resources::text(resources::Key::FindingRightsTerritoryMismatch, locale)
        }
        F::RightsScopeMismatch => {
            resources::text(resources::Key::FindingRightsScopeMismatch, locale)
        }
        F::RightsRestrictionsRequireReview => resources::text(
            resources::Key::FindingRightsRestrictionsRequireReview,
            locale,
        ),
        F::EstimateUnavailable => {
            resources::text(resources::Key::FindingEstimateUnavailable, locale)
        }
        F::BudgetExceeded => resources::text(resources::Key::FindingBudgetExceeded, locale),
        F::RevisionChanged => resources::text(resources::Key::FindingRevisionChanged, locale),
        F::SettingsChanged => resources::text(resources::Key::FindingSettingsChanged, locale),
        F::RightsChanged => resources::text(resources::Key::FindingRightsChanged, locale),
        F::ApprovalMissing => resources::text(resources::Key::FindingApprovalMissing, locale),
        F::ApprovalScopeMismatch => {
            resources::text(resources::Key::FindingApprovalScopeMismatch, locale)
        }
    }
}
