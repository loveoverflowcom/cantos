//! Workspace chrome and lifecycle resources, shared by revision and proposal shells.
use crate::localization::generated::workspace as resources;
#[derive(Clone, Copy)]
pub enum Key {
    Import,
    Proposal,
    Revisions,
    Session,
    SessionChecking,
    SessionRefresh,
    SessionLogout,
    SessionRetained,
    Workspace,
    Validate,
    Validating,
    Valid,
    ValidateHelp,
    ValidateFirst,
    ReviewBeforeSave,
    Unsaved,
    Saved,
    Discard,
    DiscardConfirm,
    History,
    HistoryHelp,
    LoadHistory,
    MoreHistory,
    OpenVersion,
    ReviewVersion,
    ReviewHelp,
    Reviewed,
    ReviewSavedConfirm,
    Source,
    SourceHelp,
    OpenSource,
    Stored,
    NoHistory,
    PermissionHelp,
    Invalidated,
    PendingReview,
    BinarySourceHelp,
    ControlReadOnly,
    ControlBlocked,
    ControlUnavailable,
    Cancel,
    DiscardNow,
    DialogFailure,
}

pub fn text(key: Key, locale: crate::localization::Locale) -> &'static str {
    match key {
        Key::ControlBlocked => resources::text(resources::Key::ControlBlocked, locale),
        Key::ControlReadOnly => resources::text(resources::Key::ControlReadOnly, locale),
        Key::ControlUnavailable => resources::text(resources::Key::ControlUnavailable, locale),
        Key::Cancel => resources::text(resources::Key::Cancel, locale),
        Key::DiscardNow => resources::text(resources::Key::DiscardNow, locale),
        Key::DialogFailure => resources::text(resources::Key::DialogFailure, locale),
        Key::Import => resources::text(resources::Key::Import, locale),
        Key::Proposal => resources::text(resources::Key::Proposal, locale),
        Key::Revisions => resources::text(resources::Key::Revisions, locale),
        Key::Session => resources::text(resources::Key::Session, locale),
        Key::SessionChecking => resources::text(resources::Key::SessionChecking, locale),
        Key::SessionRefresh => resources::text(resources::Key::SessionRefresh, locale),
        Key::SessionLogout => resources::text(resources::Key::SessionLogout, locale),
        Key::SessionRetained => resources::text(resources::Key::SessionRetained, locale),
        Key::Workspace => resources::text(resources::Key::Workspace, locale),
        Key::Validate => resources::text(resources::Key::Validate, locale),
        Key::Validating => resources::text(resources::Key::Validating, locale),
        Key::Valid => resources::text(resources::Key::Valid, locale),
        Key::ValidateHelp => resources::text(resources::Key::ValidateHelp, locale),
        Key::ValidateFirst => resources::text(resources::Key::ValidateFirst, locale),
        Key::ReviewBeforeSave => resources::text(resources::Key::ReviewBeforeSave, locale),
        Key::Unsaved => resources::text(resources::Key::Unsaved, locale),
        Key::Saved => resources::text(resources::Key::Saved, locale),
        Key::Discard => resources::text(resources::Key::Discard, locale),
        Key::DiscardConfirm => resources::text(resources::Key::DiscardConfirm, locale),
        Key::History => resources::text(resources::Key::History, locale),
        Key::HistoryHelp => resources::text(resources::Key::HistoryHelp, locale),
        Key::LoadHistory => resources::text(resources::Key::LoadHistory, locale),
        Key::MoreHistory => resources::text(resources::Key::MoreHistory, locale),
        Key::OpenVersion => resources::text(resources::Key::OpenVersion, locale),
        Key::ReviewVersion => resources::text(resources::Key::ReviewVersion, locale),
        Key::ReviewHelp => resources::text(resources::Key::ReviewHelp, locale),
        Key::ReviewSavedConfirm => resources::text(resources::Key::ReviewSavedConfirm, locale),
        Key::Reviewed => resources::text(resources::Key::Reviewed, locale),
        Key::Source => resources::text(resources::Key::Source, locale),
        Key::SourceHelp => resources::text(resources::Key::SourceHelp, locale),
        Key::OpenSource => resources::text(resources::Key::OpenSource, locale),
        Key::Stored => resources::text(resources::Key::Stored, locale),
        Key::NoHistory => resources::text(resources::Key::NoHistory, locale),
        Key::PermissionHelp => resources::text(resources::Key::PermissionHelp, locale),
        Key::Invalidated => resources::text(resources::Key::Invalidated, locale),
        Key::BinarySourceHelp => resources::text(resources::Key::BinarySourceHelp, locale),
        Key::PendingReview => resources::text(resources::Key::PendingReview, locale),
    }
}
